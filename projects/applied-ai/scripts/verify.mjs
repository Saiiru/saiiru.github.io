import {readFile,stat} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {routeWithModel} from '../core/vetor-ml.mjs';
import {compareRuns,evalCases} from '../core/crivo.mjs';
import {corpusPaths,chunkDocuments,benchmarkRetrieval} from '../core/lastro.mjs';
const root=resolve(import.meta.dirname,'..');
const json=async name=>JSON.parse(await readFile(resolve(root,name),'utf8'));
const model=await json('models/vetor.json'),ml=await json('reports/vetor.json');
assert.equal(model.datasetSha256,ml.datasetSha256);
assert.equal(ml.test.support,32);
for(const outcome of ml.test.outcomes)assert.equal(routeWithModel(outcome.text,model).team,outcome.label);
const docs=await Promise.all(corpusPaths.map(async path=>({path,text:await readFile(resolve(root,path),'utf8')})));
const expected=benchmarkRetrieval(await json('lastro/queries.json'),chunkDocuments(docs),3);
const actual=await json('reports/lastro.json');
for(const key of ['total','recallAtK','mrr','noAnswerAccuracy'])assert.equal(expected[key],actual[key]);
assert.deepEqual(compareRuns(evalCases,{},await json('crivo/examples/candidate.json')).regressions,(await json('reports/crivo.json')).regressions);
for(const file of ['README.md','crivo/README.md','vetor/README.md','vetor/MODEL_CARD.md','lastro/README.md','EXPERIMENT.md','BENCHMARK.md','ml/train.py'])assert((await stat(resolve(root,file))).size>100);
const html=await readFile(resolve(root,'index.html'),'utf8');
for(const id of ['crivo','vetor','lastro'])assert(html.includes(`panel-${id}`));
assert(!/<script[^>]+src=["']https?:/i.test(html));
console.log('VERIFY OK: model/report agreement, recalculated retrieval, regressions, project docs and demo panels.');
