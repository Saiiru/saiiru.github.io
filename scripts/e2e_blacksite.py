from playwright.sync_api import sync_playwright
BASE="http://127.0.0.1:4389"
def verify():
 with sync_playwright() as p:
  browser=p.chromium.launch(headless=True,executable_path="/usr/bin/chromium",args=["--no-sandbox","--disable-gpu"])
  page=browser.new_page(viewport={"width":1440,"height":900},accept_downloads=True)
  errors=[]
  page.on("pageerror",lambda e:errors.append(str(e)))
  page.goto(BASE+"/",wait_until="domcontentloaded")
  page.wait_for_timeout(700)
  assert "S4IRU" in page.title(),page.title()
  assert page.locator(".lab-card").count()==3
  assert page.locator("a[href^='/labs/index.html']").count()>=3
  page.locator("#terminal-input").fill("help")
  page.locator("#terminal-input").press("Enter")
  assert "help" in page.locator(".terminal-output").inner_text().lower()
  assert page.locator(".tech-chip").count()==9
  chip=page.get_by_role("button",name="Inspecionar competência: Fluxo / Aprovação")
  chip.click()
  assert chip.get_attribute("aria-pressed")=="true"
  assert "OpsPilot" in page.locator(".inspector-detail").inner_text()
  assert not errors,errors
  print("PASS portfolio desktop, terminal, three labs, JS clean")
  page.goto(BASE+"/labs/index.html?lab=evalforge",wait_until="domcontentloaded")
  assert page.locator("#panel-evalforge").is_visible()
  page.locator("#ef-run").click()
  assert "6 de 6" in page.locator("#ef-status").inner_text()
  page.locator("#ef-response").fill("completely wrong")
  page.locator("#ef-run").click()
  assert page.locator("#ef-status").inner_text().startswith("5 de 6")
  print("PASS EvalForge evaluation reacts to changed answer")
  page.goto(BASE+"/labs/index.html?lab=opspilot",wait_until="domcontentloaded")
  assert page.locator("#panel-opspilot").is_visible()
  assert page.locator("#op-export").is_disabled()
  page.locator("#op-approve").click()
  assert page.locator("#op-export").is_enabled()
  page.locator("#op-text").fill("Novo texto sem classificação")
  assert page.locator("#op-export").is_disabled()
  page.locator("#op-route").click()
  page.locator("#op-approve").click()
  with page.expect_download() as download:
   page.locator("#op-export").click()
  print("PASS OpsPilot manual approval gate and JSON export",download.value.suggested_filename)
  page.goto(BASE+"/labs/index.html?lab=doctrace",wait_until="domcontentloaded")
  page.wait_for_timeout(400)
  assert page.locator("#panel-doctrace").is_visible()
  assert "6 documentos" in page.locator("#dt-status").inner_text()
  page.locator("#dt-query").fill("cobrança duplicada")
  page.locator("#dt-search").click()
  assert "pagamentos.md" in page.locator("#dt-results").inner_text().lower()
  page.locator("#dt-query").fill("xylophonia123 abczzz123")
  page.locator("#dt-search").click()
  assert "Não encontrei" in page.locator("#dt-answer").inner_text()
  print("PASS DocTrace citations and out-of-corpus refusal")
  mobile=browser.new_page(viewport={"width":390,"height":844})
  mobile.goto(BASE+"/",wait_until="domcontentloaded")
  mobile.wait_for_timeout(350)
  assert mobile.locator(".menu-button").is_visible()
  assert mobile.evaluate("document.documentElement.scrollWidth <= window.innerWidth + 2"),("overflow",mobile.evaluate("document.documentElement.scrollWidth"))
  mobile.locator(".menu-button").click()
  assert mobile.locator(".nav-links").is_visible()
  print("PASS mobile 390px: menu, no horizontal overflow")
  browser.close()
verify()
